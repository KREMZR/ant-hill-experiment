/* Minimal static file server for previewing the simulation: node tools/serve.js */
'use strict';
var http = require('http'), fs = require('fs'), path = require('path');
var rootDir = path.join(__dirname, '..'), port = +process.env.PORT || 4173;
var types = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
http.createServer(function (req, res) {
  var rel = decodeURIComponent(req.url.split('?')[0]);
  if (rel === '/') rel = '/index.html';
  var file = path.normalize(path.join(rootDir, rel));
  if (file.indexOf(rootDir) !== 0) { res.writeHead(403); res.end(); return; }
  fs.readFile(file, function (err, data) {
    if (err) { res.writeHead(404); res.end('Not found'); return; }
    res.writeHead(200, { 'Content-Type': types[path.extname(file)] || 'application/octet-stream', 'Cache-Control': 'no-store' });
    res.end(data);
  });
}).listen(port, '127.0.0.1', function () { console.log('Ant hill at http://localhost:' + port); });
